import 'package:cloud_firestore/cloud_firestore.dart';
import '../../domain/entities/farm_entity.dart';

class FarmModel extends FarmEntity {
  const FarmModel({
    required super.id,
    required super.ownerId,
    required super.ownerName,
    required super.title,
    required super.description,
    required super.lat,
    required super.lng,
    required super.geohash,
    required super.village,
    required super.district,
    required super.state,
    required super.areaSqMeters,
    required super.areaUnit,
    required super.fodderTypes,
    required super.pricePerDayPerAnimal,
    required super.maxAnimals,
    super.hasWater,
    super.hasShade,
    super.hasFencing,
    super.hasVetNearby,
    super.imageUrls,
    super.isAvailable,
    super.rating,
    super.reviewCount,
    required super.createdAt,
    super.availableFrom,
    super.availableTo,
  });

  factory FarmModel.fromFirestore(DocumentSnapshot<Map<String, dynamic>> doc) {
    final d = doc.data()!;
    return FarmModel(
      id: doc.id,
      ownerId: d['ownerId'] as String? ?? '',
      ownerName: d['ownerName'] as String? ?? '',
      title: d['title'] as String? ?? '',
      description: d['description'] as String? ?? '',
      lat: (d['lat'] as num?)?.toDouble() ?? 0,
      lng: (d['lng'] as num?)?.toDouble() ?? 0,
      geohash: d['geohash'] as String? ?? '',
      village: d['village'] as String? ?? '',
      district: d['district'] as String? ?? '',
      state: d['state'] as String? ?? '',
      areaSqMeters: (d['areaSqMeters'] as num?)?.toDouble() ?? 0,
      areaUnit: d['areaUnit'] as String? ?? 'acre',
      fodderTypes: List<String>.from(d['fodderTypes'] as List? ?? []),
      pricePerDayPerAnimal: (d['pricePerDayPerAnimal'] as num?)?.toDouble() ?? 0,
      maxAnimals: (d['maxAnimals'] as num?)?.toInt() ?? 0,
      hasWater: d['hasWater'] as bool? ?? false,
      hasShade: d['hasShade'] as bool? ?? false,
      hasFencing: d['hasFencing'] as bool? ?? false,
      hasVetNearby: d['hasVetNearby'] as bool? ?? false,
      imageUrls: List<String>.from(d['imageUrls'] as List? ?? []),
      isAvailable: d['isAvailable'] as bool? ?? true,
      rating: (d['rating'] as num?)?.toDouble() ?? 0,
      reviewCount: (d['reviewCount'] as num?)?.toInt() ?? 0,
      createdAt: (d['createdAt'] as Timestamp?)?.toDate() ?? DateTime.now(),
      availableFrom: (d['availableFrom'] as Timestamp?)?.toDate(),
      availableTo: (d['availableTo'] as Timestamp?)?.toDate(),
    );
  }

  Map<String, dynamic> toFirestore() => {
    'ownerId': ownerId,
    'ownerName': ownerName,
    'title': title,
    'description': description,
    'lat': lat,
    'lng': lng,
    'geohash': geohash,
    'village': village,
    'district': district,
    'state': state,
    'areaSqMeters': areaSqMeters,
    'areaUnit': areaUnit,
    'fodderTypes': fodderTypes,
    'pricePerDayPerAnimal': pricePerDayPerAnimal,
    'maxAnimals': maxAnimals,
    'hasWater': hasWater,
    'hasShade': hasShade,
    'hasFencing': hasFencing,
    'hasVetNearby': hasVetNearby,
    'imageUrls': imageUrls,
    'isAvailable': isAvailable,
    'rating': rating,
    'reviewCount': reviewCount,
    'createdAt': Timestamp.fromDate(createdAt),
    if (availableFrom != null) 'availableFrom': Timestamp.fromDate(availableFrom!),
    if (availableTo != null) 'availableTo': Timestamp.fromDate(availableTo!),
  };

  FarmModel copyWithModel({
    String? title,
    String? description,
    double? lat,
    double? lng,
    String? geohash,
    String? village,
    String? district,
    String? state,
    double? areaSqMeters,
    String? areaUnit,
    List<String>? fodderTypes,
    double? pricePerDayPerAnimal,
    int? maxAnimals,
    bool? hasWater,
    bool? hasShade,
    bool? hasFencing,
    bool? hasVetNearby,
    List<String>? imageUrls,
    bool? isAvailable,
  }) => FarmModel(
    id: id,
    ownerId: ownerId,
    ownerName: ownerName,
    title: title ?? this.title,
    description: description ?? this.description,
    lat: lat ?? this.lat,
    lng: lng ?? this.lng,
    geohash: geohash ?? this.geohash,
    village: village ?? this.village,
    district: district ?? this.district,
    state: state ?? this.state,
    areaSqMeters: areaSqMeters ?? this.areaSqMeters,
    areaUnit: areaUnit ?? this.areaUnit,
    fodderTypes: fodderTypes ?? this.fodderTypes,
    pricePerDayPerAnimal: pricePerDayPerAnimal ?? this.pricePerDayPerAnimal,
    maxAnimals: maxAnimals ?? this.maxAnimals,
    hasWater: hasWater ?? this.hasWater,
    hasShade: hasShade ?? this.hasShade,
    hasFencing: hasFencing ?? this.hasFencing,
    hasVetNearby: hasVetNearby ?? this.hasVetNearby,
    imageUrls: imageUrls ?? this.imageUrls,
    isAvailable: isAvailable ?? this.isAvailable,
    rating: rating,
    reviewCount: reviewCount,
    createdAt: createdAt,
    availableFrom: availableFrom,
    availableTo: availableTo,
  );
}
